"""Builds web/lang_sw.js (English -> Kiswahili dictionary) from the translation files in tools/i18n."""
import json, os, glob, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)


def norm(s):
    return " ".join(s.split())


def build():
    en = json.load(open(os.path.join(HERE, "en_instrument.json"), encoding="utf-8"))
    sw = []
    for f in sorted(glob.glob(os.path.join(HERE, "sw_instrument_*.txt"))):
        sw += open(f, encoding="utf-8").read().rstrip("\n").split("\n")
    if len(sw) != len(en):
        raise SystemExit("i18n: %d English strings but %d Kiswahili lines" % (len(en), len(sw)))
    d = {}
    for e, s in zip(en, sw):
        if norm(e) != norm(s):
            d[norm(e)] = s.strip()
    import importlib
    ui = importlib.import_module("sw_ui")
    for e, s in ui.UI.items():
        d[norm(e)] = s.strip()
    rx = list(ui.RX)
    sp = importlib.import_module("sw_portal")
    for e, s in sp.UI.items():
        d[norm(e)] = s.strip()
    rx += sp.RX
    js = "/* GENERATED by tools/i18n/build_dict.py. Kiswahili is a DRAFT until a translator has checked it. */\nwindow.SW_DICT=" + json.dumps(d, ensure_ascii=False, separators=(",", ":")) + ";\nwindow.SW_RX=[" + ",".join("[/%s/,%s]" % (a, b) for a, b in rx) + "];\n"
    return js, d


if __name__ == "__main__":
    js, d = build(); print(len(d), "entries")
